-- Relic Route: OLTP source for the pet DWH.
-- Schema `relic` = product domain (phase 2+).
-- Schema `raw`  = legacy demo table; kept so existing Airflow/Spark DAGs still run until phase 3.
-- All TIMESTAMP columns hold UTC; business dates (van_stops.stop_date) are Moscow dates.

CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS relic;

-- Required for Debezium CDC (logical replication)
ALTER ROLE source WITH REPLICATION;

