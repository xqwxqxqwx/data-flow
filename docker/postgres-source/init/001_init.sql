-- ---------------------------------------------------------------------------
-- Relic Route OLTP
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS relic.customers (
  customer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  full_name     TEXT NOT NULL,
  city          TEXT NOT NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS relic.items (
  item_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title         TEXT NOT NULL,
  category      TEXT NOT NULL,
  brand         TEXT,
  grade         TEXT NOT NULL CHECK (grade IN ('S', 'A', 'B', 'C')),
  status        TEXT NOT NULL CHECK (status IN ('sourced', 'listed', 'reserved', 'sold', 'archived')),
  list_price    NUMERIC(12,2) NOT NULL CHECK (list_price >= 0),
  listed_at     TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS relic.vans (
  van_id        BIGINT PRIMARY KEY,
  name          TEXT NOT NULL,
  van_type      TEXT NOT NULL CHECK (van_type IN ('cargo_bike', 'van', 'popup_box'))
);

CREATE TABLE IF NOT EXISTS relic.stop_locations (
  location_id   BIGINT PRIMARY KEY,
  name          TEXT NOT NULL,
  district      TEXT NOT NULL,
  lat           NUMERIC(9,6),
  lon           NUMERIC(9,6)
);

CREATE TABLE IF NOT EXISTS relic.van_stops (
  stop_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  van_id        BIGINT NOT NULL REFERENCES relic.vans (van_id),
  location_id   BIGINT NOT NULL REFERENCES relic.stop_locations (location_id),
  stop_date     DATE NOT NULL,
  started_at    TIMESTAMP NOT NULL,
  ended_at      TIMESTAMP,
  CONSTRAINT uq_van_stops_day UNIQUE (van_id, location_id, stop_date),
  CONSTRAINT chk_van_stops_window CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE IF NOT EXISTS relic.orders (
  order_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   BIGINT NOT NULL REFERENCES relic.customers (customer_id),
  order_ts      TIMESTAMP NOT NULL,
  channel       TEXT NOT NULL CHECK (channel IN ('online', 'van')),
  status        TEXT NOT NULL CHECK (status IN ('created', 'paid', 'fulfilled', 'cancelled')),
  currency      TEXT NOT NULL DEFAULT 'RUB',
  total_amount  NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
  van_id        BIGINT REFERENCES relic.vans (van_id),
  stop_id       BIGINT REFERENCES relic.van_stops (stop_id),
  updated_at    TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_orders_channel_van CHECK (
    (channel = 'online' AND van_id IS NULL AND stop_id IS NULL)
    OR (channel = 'van' AND van_id IS NOT NULL AND stop_id IS NOT NULL)
  )
);

CREATE TABLE IF NOT EXISTS relic.order_items (
  order_id      BIGINT NOT NULL REFERENCES relic.orders (order_id),
  item_id       BIGINT NOT NULL REFERENCES relic.items (item_id),
  unit_price    NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
  qty           INT NOT NULL DEFAULT 1 CHECK (qty > 0),
  PRIMARY KEY (order_id, item_id)
);

-- Home delivery for online orders (van orders are handed over on the spot).
CREATE TABLE IF NOT EXISTS relic.deliveries (
  delivery_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT NOT NULL UNIQUE REFERENCES relic.orders (order_id),
  method        TEXT NOT NULL CHECK (method IN ('courier', 'post', 'pickup_point')),
  city          TEXT NOT NULL,
  address       TEXT NOT NULL,
  status        TEXT NOT NULL CHECK (status IN ('pending', 'shipped', 'delivered', 'returned', 'cancelled')),
  delivery_fee  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
  created_at    TIMESTAMP NOT NULL DEFAULT NOW(),
  shipped_at    TIMESTAMP,
  delivered_at  TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_deliveries_timeline CHECK (
    (shipped_at IS NULL OR shipped_at >= created_at)
    AND (delivered_at IS NULL OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at))
  )
);

CREATE INDEX IF NOT EXISTS idx_relic_items_status ON relic.items (status);
CREATE INDEX IF NOT EXISTS idx_relic_orders_ts ON relic.orders (order_ts);
CREATE INDEX IF NOT EXISTS idx_relic_orders_channel ON relic.orders (channel);
CREATE INDEX IF NOT EXISTS idx_relic_van_stops_date ON relic.van_stops (stop_date);
CREATE INDEX IF NOT EXISTS idx_relic_order_items_item ON relic.order_items (item_id);
CREATE INDEX IF NOT EXISTS idx_relic_deliveries_status ON relic.deliveries (status);

