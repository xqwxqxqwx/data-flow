-- Phase 1: bring an already-initialised postgres-source volume up to date with init/001_init.sql.
-- Idempotent: safe to run more than once.
--
--   docker compose exec -T postgres-source psql -U source -d source -v ON_ERROR_STOP=1 \
--     < docker/postgres-source/migrations/001_phase1_deliveries.sql

BEGIN;

-- Identity ids, so the live simulator can insert without computing max(id) + 1.
DO $$
DECLARE
  t record;
BEGIN
  FOR t IN
    SELECT * FROM (VALUES
      ('customers', 'customer_id'),
      ('items', 'item_id'),
      ('van_stops', 'stop_id'),
      ('orders', 'order_id')
    ) AS v(tbl, col)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'relic' AND table_name = t.tbl
        AND column_name = t.col AND is_identity = 'YES'
    ) THEN
      EXECUTE format('ALTER TABLE relic.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY', t.tbl, t.col);
    END IF;
  END LOOP;
END $$;

ALTER TABLE relic.orders ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT NOW();

CREATE TABLE IF NOT EXISTS relic.deliveries (
  delivery_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT NOT NULL UNIQUE REFERENCES relic.orders (order_id),
  method        TEXT NOT NULL CHECK (method IN ('courier', 'post', 'pickup_point')),
  city          TEXT NOT NULL,
  address       TEXT NOT NULL,
  status        TEXT NOT NULL CHECK (status IN ('pending', 'shipped', 'delivered', 'returned', 'cancelled')),
  delivery_fee  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
  created_at    TIMESTAMP NOT NULL DEFAULT NOW(),
  shipped_at    TIMESTAMP,
  delivered_at  TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_deliveries_timeline CHECK (
    (shipped_at IS NULL OR shipped_at >= created_at)
    AND (delivered_at IS NULL OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at))
  )
);

CREATE INDEX IF NOT EXISTS idx_relic_order_items_item ON relic.order_items (item_id);
CREATE INDEX IF NOT EXISTS idx_relic_deliveries_status ON relic.deliveries (status);

-- Move identity sequences past existing ids.
SELECT setval(pg_get_serial_sequence('relic.customers', 'customer_id'), COALESCE((SELECT MAX(customer_id) FROM relic.customers), 0) + 1, false);
SELECT setval(pg_get_serial_sequence('relic.items', 'item_id'), COALESCE((SELECT MAX(item_id) FROM relic.items), 0) + 1, false);
SELECT setval(pg_get_serial_sequence('relic.van_stops', 'stop_id'), COALESCE((SELECT MAX(stop_id) FROM relic.van_stops), 0) + 1, false);
SELECT setval(pg_get_serial_sequence('relic.orders', 'order_id'), COALESCE((SELECT MAX(order_id) FROM relic.orders), 0) + 1, false);

COMMIT;
